package bootstraptools

import (
	"crypto/sha256"
	_ "embed"
	"encoding/base64"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"

	"github.com/sagmans/serverpro/internal/shell"
)

const (
	// The install project, its digest, and the probe travel as environment
	// values so bootstrap, its local repair, and doctor all read one Go-owned
	// copy of the reviewed tree.
	piPackageJSONEnv = "SERVERPRO_BOOTSTRAP_PI_PACKAGE_JSON_BASE64"
	piLockEnv        = "SERVERPRO_BOOTSTRAP_PI_LOCK_BASE64"
	piLockSHA256Env  = "SERVERPRO_BOOTSTRAP_PI_LOCK_SHA256"
	piBinEnv         = "SERVERPRO_BOOTSTRAP_PI_BIN"
	piLockProbeEnv   = "SERVERPRO_BOOTSTRAP_PI_LOCK_PROBE_BASE64"
	// The registry is passed to npm explicitly so a host or user .npmrc
	// cannot redirect the reviewed downloads to another origin.
	piRegistryEnv = "SERVERPRO_BOOTSTRAP_PI_REGISTRY"

	// PiInstallDirectory is the install project directory under the Node
	// install's lib/. It sits next to npm's global lib/node_modules rather than
	// inside it, so a later `npm install -g` never rewrites the reviewed tree,
	// and it shares the Node install's lifecycle: a Node reinstall or prune
	// removes it with the Node that runs it.
	PiInstallDirectory = "serverpro-pi"
	// piLockRegistry is the only origin the reviewed lock may download from.
	piLockRegistry = "https://registry.npmjs.org/"
	// piLockfileVersion is the npm 7+ lock format that `npm ci` reads without
	// rewriting it.
	piLockfileVersion = 3
	piLockBinName     = "pi"
)

// The lock is generated by scripts/update-pi-lock.sh and reviewed in Git;
// embedding it keeps the binary, the manual wrapper, and doctor on one tree.
var (
	//go:embed pi/package.json
	piPackageJSON []byte
	//go:embed pi/package-lock.json
	piLockJSON []byte
)

// piLockEntry is the subset of an npm lockfile package entry that serverpro
// trusts. Unknown fields stay with npm.
type piLockEntry struct {
	Version      string            `json:"version"`
	Resolved     string            `json:"resolved"`
	Integrity    string            `json:"integrity"`
	Dev          bool              `json:"dev"`
	Link         bool              `json:"link"`
	Dependencies map[string]string `json:"dependencies"`
	Bin          map[string]string `json:"bin"`
}

type piLockFile struct {
	Name            string                 `json:"name"`
	LockfileVersion int                    `json:"lockfileVersion"`
	Packages        map[string]piLockEntry `json:"packages"`
}

type piProject struct {
	Name         string            `json:"name"`
	Dependencies map[string]string `json:"dependencies"`
}

// piLockedTree is what the rest of the package needs from the reviewed lock.
type piLockedTree struct {
	sha256   string
	bin      string
	packages int
}

var (
	piIntegrityPattern = regexp.MustCompile(`^sha512-[A-Za-z0-9+/]{86}==$`)
	// The bin path reaches a shell symlink command, so it stays a plain
	// relative path inside the Pi package.
	piBinPattern = regexp.MustCompile(`^[A-Za-z0-9._-]+(/[A-Za-z0-9._-]+)*$`)
)

// piLock is validated once at start-up. A broken embedded lock is a build
// defect, so failing every command at once is safer than installing an
// unreviewed tree on one host.
var piLock = mustLoadPiLock(piPackageJSON, piLockJSON)

func mustLoadPiLock(project, lock []byte) piLockedTree {
	tree, err := loadPiLock(project, lock)
	if err != nil {
		panic(fmt.Sprintf("embedded Pi lock (internal/bootstraptools/pi) is invalid; rerun scripts/update-pi-lock.sh %s: %v", PiVersion, err))
	}
	return tree
}

// loadPiLock fails closed unless the lock installs exactly PiVersion and
// every package is an integrity-pinned production download from the npm
// registry.
func loadPiLock(project, lock []byte) (piLockedTree, error) {
	var pkg piProject
	if err := json.Unmarshal(project, &pkg); err != nil {
		return piLockedTree{}, fmt.Errorf("parse package.json: %w", err)
	}
	var file piLockFile
	if err := json.Unmarshal(lock, &file); err != nil {
		return piLockedTree{}, fmt.Errorf("parse package-lock.json: %w", err)
	}
	want := map[string]string{PiToolName: PiVersion}
	if !equalDependencies(pkg.Dependencies, want) {
		return piLockedTree{}, fmt.Errorf("package.json dependencies = %v, want %v", pkg.Dependencies, want)
	}
	if file.LockfileVersion != piLockfileVersion || file.Name != pkg.Name {
		return piLockedTree{}, fmt.Errorf("lock name %q version %d, want %q version %d", file.Name, file.LockfileVersion, pkg.Name, piLockfileVersion)
	}
	if root := file.Packages[""]; !equalDependencies(root.Dependencies, want) {
		return piLockedTree{}, fmt.Errorf("lock root dependencies = %v, want %v", root.Dependencies, want)
	}
	count := 0
	for path, entry := range file.Packages {
		if path == "" {
			continue
		}
		if !strings.HasPrefix(path, "node_modules/") || strings.Contains(path, "..") {
			return piLockedTree{}, fmt.Errorf("lock path %q is outside node_modules", path)
		}
		if entry.Dev || entry.Link {
			return piLockedTree{}, fmt.Errorf("lock entry %q is a dev or linked package", path)
		}
		if entry.Version == "" || !strings.HasPrefix(entry.Resolved, piLockRegistry) || !piIntegrityPattern.MatchString(entry.Integrity) {
			return piLockedTree{}, fmt.Errorf("lock entry %q lacks a registry download with sha512 integrity", path)
		}
		count++
	}
	pi, ok := file.Packages["node_modules/"+PiToolName]
	if !ok || pi.Version != PiVersion {
		return piLockedTree{}, fmt.Errorf("lock installs %s %q, want %s", PiToolName, pi.Version, PiVersion)
	}
	bin := strings.TrimPrefix(pi.Bin[piLockBinName], "./")
	if !piBinPattern.MatchString(bin) || strings.Contains(bin, "..") {
		return piLockedTree{}, fmt.Errorf("lock %s bin %q is not a plain relative path", piLockBinName, pi.Bin[piLockBinName])
	}
	sum := sha256.Sum256(lock)
	return piLockedTree{sha256: hex.EncodeToString(sum[:]), bin: bin, packages: count}, nil
}

func equalDependencies(got, want map[string]string) bool {
	if len(got) != len(want) {
		return false
	}
	for name, version := range want {
		if got[name] != version {
			return false
		}
	}
	return true
}

// piLockProbe proves a Pi install still matches the reviewed lock. It reads
// package metadata only, so verification never runs dependency code. The
// digest proves the lock on disk is the reviewed one; the per-package
// versions prove the tree on disk is what that lock installed.
const piLockProbe = `const { createHash } = require("node:crypto");
const { readFileSync } = require("node:fs");
const { join } = require("node:path");
const [root, expectedSha] = process.argv.slice(1);
const fail = (message) => { console.error(message); process.exit(1); };
if (!root || !/^[0-9a-f]{64}$/.test(expectedSha || "")) fail("invalid Pi lock probe arguments");
let raw;
try { raw = readFileSync(join(root, "package-lock.json")); } catch { fail("Pi lockfile missing at " + root + "; rerun managed bootstrap"); }
const actualSha = createHash("sha256").update(raw).digest("hex");
if (actualSha !== expectedSha) fail("Pi lockfile is not the reviewed lockfile: sha256 " + actualSha + ", want " + expectedSha);
const packages = JSON.parse(raw).packages || {};
let count = 0;
for (const [path, entry] of Object.entries(packages)) {
  if (path === "") continue;
  let installed = "missing";
  try { installed = JSON.parse(readFileSync(join(root, path, "package.json"), "utf8")).version; } catch {}
  if (installed !== entry.version) fail("expected Pi dependency " + path.slice(path.lastIndexOf("node_modules/") + 13) + " " + entry.version + ", got " + installed);
  count++;
}
console.log("Pi lockfile sha256 " + actualSha + " (" + count + " packages)");`

// piLockEnvPairs is the manifest slice that carries the reviewed install
// project to the host.
func piLockEnvPairs() [][2]string {
	return [][2]string{
		{piPackageJSONEnv, base64.StdEncoding.EncodeToString(piPackageJSON)},
		{piLockEnv, base64.StdEncoding.EncodeToString(piLockJSON)},
		{piLockSHA256Env, piLock.sha256},
		{piBinEnv, piLock.bin},
		{piLockProbeEnv, base64.StdEncoding.EncodeToString([]byte(piLockProbe))},
		{piRegistryEnv, piLockRegistry},
	}
}

// piCheckCommand is doctor's copy of the readiness probe the bootstrap shell
// builds from the same manifest, so both reach one trust decision: pi on PATH
// is the Node install's link, the link points into the reviewed project, the
// project matches the reviewed lock, and the CLI reports PiVersion.
func piCheckCommand() string {
	nodeRoot := `$HOME/.local/share/mise/installs/node/` + NodeVersion
	piRoot := nodeRoot + `/lib/` + PiInstallDirectory
	return `expected_pi="` + nodeRoot + `/bin/pi"; actual_pi=$("$HOME/.local/bin/mise" exec -- sh -c 'command -v pi'); test "$actual_pi" = "$expected_pi" || { printf 'expected pi at %s, got %s\n' "$expected_pi" "$actual_pi" >&2; exit 1; }; ` +
		`pi_target=$(readlink -f "$expected_pi"); want_target=$(readlink -f "` + piRoot + `")/node_modules/` + PiToolName + `/` + piLock.bin + `; test "$pi_target" = "$want_target" || { printf 'expected pi to link to %s, got %s; rerun managed bootstrap\n' "$want_target" "$pi_target" >&2; exit 1; }; ` +
		`"$HOME/.local/bin/mise" exec -- node -e ` + shell.Quote(piLockProbe) + ` "` + piRoot + `" ` + piLock.sha256 + `; ` +
		`pi_version=$("$HOME/.local/bin/mise" exec -- pi --version 2>&1) || { status=$?; printf 'pi --version failed (%s): %s\n' "$status" "$pi_version" >&2; exit "$status"; }; test "$pi_version" = "` + PiVersion + `" || { printf 'expected pi ` + PiVersion + `, got %s\n' "$pi_version" >&2; exit 1; }; printf '%s\n' "$pi_version"`
}
