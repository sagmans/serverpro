#!/usr/bin/env bash
# Format-check and lint repo-owned shell and Python scripts at the exact
# versions pinned in mise.toml. Shared by `make lint-shell`, `make lint-python`,
# and `.githooks/pre-commit.d/35-scripts` so local, commit, and push gates stay
# identical and fail closed on missing or mismatched tools.
# Usage:
#   scripts/lint-scripts.sh [--shell|--python|--all] [--] [paths...]
#   scripts/lint-scripts.sh --filter
set -euo pipefail

# Explicit isolated Ruff settings so host configs or future defaults never shift hooks.
readonly RUFF_SELECT='E,F,W,I,B,UP'
# Delegate line wrapping to `ruff format` so unbreakable strings/URLs are not double-checked.
readonly RUFF_IGNORE='E501'
readonly RUFF_TARGET_VERSION='py39'
readonly MISE_CONFIG_REL='mise.toml'
readonly TEMPLATE_SETUP_HOOKS='scripts/setup-hooks'
# Generated by `make gen-bootstrap-wrapper` (internal/bootstraptools/bootstrap.go)
# and its embedded canonical template (asserted verbatim by Go unit tests in
# internal/bootstraptools/bootstrap*_test.go): both are linted by shellcheck
# and excluded from shfmt so formatting never breaks generator or test contracts.
readonly GENERATED_WRAPPER='scripts/serverpro-bootstrap-tools.sh'
readonly EMBEDDED_BOOTSTRAP='internal/bootstraptools/serverpro-bootstrap-tools.sh'

# Single authority for repo-owned shell and Python target classification.
classify_rel_path() {
	case "$1" in
	"$TEMPLATE_SETUP_HOOKS" | .githooks/lib/* | .githooks/pre-commit | .githooks/pre-merge-commit | .githooks/prepare-commit-msg | .githooks/commit-msg | .githooks/pre-push)
		return 1
		;;
	*.[pP][yY])
		printf 'python\n'
		return 0
		;;
	*.[sS][hH])
		printf 'shell\n'
		return 0
		;;
	.githooks/*.d/*)
		printf 'shell\n'
		return 0
		;;
	*)
		return 1
		;;
	esac
}

is_shfmt_excluded() {
	case "$1" in
	"$GENERATED_WRAPPER" | "$EMBEDDED_BOOTSTRAP") return 0 ;;
	*) return 1 ;;
	esac
}

if [ "${1:-}" = "--filter" ]; then
	if [ "$#" -ne 1 ]; then
		echo "lint-scripts: --filter accepts no extra arguments" >&2
		exit 2
	fi
	while IFS= read -r -d '' path; do
		if classify_rel_path "$path" >/dev/null; then
			printf '%s\0' "$path"
		fi
	done
	exit 0
fi

mode="all"
while [ "$#" -gt 0 ]; do
	case "$1" in
	--shell)
		mode="shell"
		shift
		;;
	--python)
		mode="python"
		shift
		;;
	--all)
		mode="all"
		shift
		;;
	--)
		shift
		break
		;;
	-*)
		echo "lint-scripts: unknown option: $1" >&2
		exit 2
		;;
	*)
		break
		;;
	esac
done

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
repo_root=$(cd -- "$script_dir/.." && pwd -P)
mise_config="$repo_root/$MISE_CONFIG_REL"

# shellcheck source=scripts/lib-mise-pin.sh
. "$script_dir/lib-mise-pin.sh"

# Resolve explicit arguments against caller $PWD into canonical $repo_root-relative
# paths, failing closed on missing files, symlinks, or paths outside $repo_root.
normalize_explicit_path() {
	local raw="$1"
	local dir base abs
	if [ -L "$raw" ]; then
		echo "lint-scripts: refusing symlink target: $raw" >&2
		exit 1
	fi
	if [ ! -f "$raw" ]; then
		echo "lint-scripts: target file not found: $raw" >&2
		exit 1
	fi
	dir=$(dirname -- "$raw")
	base=$(basename -- "$raw")
	abs="$(cd -- "$dir" && pwd -P)/$base"
	case "$abs" in
	"$repo_root"/*)
		printf '%s\n' "${abs#"$repo_root/"}"
		;;
	*)
		echo "lint-scripts: path outside repository root ($repo_root): $raw" >&2
		exit 1
		;;
	esac
}

shellcheck_files=()
shfmt_files=()
python_files=()

add_target() {
	local rel="$1"
	local kind
	if ! kind="$(classify_rel_path "$rel")"; then
		return 1
	fi
	case "$kind" in
	python)
		if [ "$mode" = "python" ] || [ "$mode" = "all" ]; then
			python_files+=("$rel")
			return 0
		fi
		return 1
		;;
	shell)
		if [ "$mode" = "shell" ] || [ "$mode" = "all" ]; then
			shellcheck_files+=("$rel")
			if ! is_shfmt_excluded "$rel"; then
				shfmt_files+=("$rel")
			fi
			return 0
		fi
		return 1
		;;
	esac
	return 1
}

if [ "$#" -eq 0 ]; then
	cd "$repo_root"
	ls_file="$(mktemp "${TMPDIR:-/tmp}/serverpro-lint-ls.XXXXXX")"
	cleanup_ls() {
		case "$ls_file" in
		*/serverpro-lint-ls.*) rm -f -- "$ls_file" ;;
		esac
	}
	trap cleanup_ls EXIT
	trap 'exit 129' HUP
	trap 'exit 130' INT
	trap 'exit 143' TERM
	git -C "$repo_root" ls-files --stage -z >"$ls_file"
	while IFS= read -r -d '' entry; do
		mode_bits="${entry%% *}"
		path="${entry#*	}"
		case "$mode_bits" in
		100644 | 100755) ;;
		*) continue ;;
		esac
		[ -f "$path" ] && [ ! -L "$path" ] || continue
		add_target "$path" || true
	done <"$ls_file"
	cleanup_ls
	trap - EXIT HUP INT TERM

	if { [ "$mode" = "shell" ] || [ "$mode" = "all" ]; } && [ "${#shellcheck_files[@]}" -eq 0 ]; then
		echo "lint-scripts: no Git-tracked repo shell scripts found; run from a Git checkout" >&2
		exit 1
	fi
	if { [ "$mode" = "python" ] || [ "$mode" = "all" ]; } && [ "${#python_files[@]}" -eq 0 ]; then
		echo "lint-scripts: no Git-tracked Python files found; run from a Git checkout" >&2
		exit 1
	fi
else
	for arg in "$@"; do
		rel="$(normalize_explicit_path "$arg")"
		if ! add_target "$rel"; then
			echo "lint-scripts: unsupported, excluded, or mode-mismatched target path: $arg" >&2
			exit 1
		fi
	done
	cd "$repo_root"
fi

# Resolve exact tool@version install dirs without reading $PWD/mise.toml so
# staged snapshots and detached at_sha worktrees succeed under MISE_PARANOID=1.
pin_specs=()
sc_pin=""
shfmt_pin=""
ruff_pin=""

if [ "${#shellcheck_files[@]}" -gt 0 ]; then
	sc_pin="$(parse_mise_pin "$mise_config" shellcheck)"
	shfmt_pin="$(parse_mise_pin "$mise_config" shfmt)"
	pin_specs+=("shellcheck@$sc_pin" "shfmt@$shfmt_pin")
fi
if [ "${#python_files[@]}" -gt 0 ]; then
	ruff_pin="$(parse_mise_pin "$mise_config" ruff)"
	pin_specs+=("ruff@$ruff_pin")
fi

if [ "${#pin_specs[@]}" -gt 0 ]; then
	prepend_pinned_mise_paths "$repo_root" "${pin_specs[@]}"
fi

if [ "${#shellcheck_files[@]}" -gt 0 ]; then
	require_pinned_tool shellcheck "$sc_pin" '--version' 's/^version: *//p'
	require_pinned_tool shfmt "$shfmt_pin" '--version' '1s/^v//p'

	shellcheck -x -- "${shellcheck_files[@]}"
	if [ "${#shfmt_files[@]}" -gt 0 ]; then
		shfmt -d -- "${shfmt_files[@]}"
	fi
fi

if [ "${#python_files[@]}" -gt 0 ]; then
	require_pinned_tool ruff "$ruff_pin" '--version' '1s/^ruff //p'

	ruff format --isolated --no-cache --target-version "$RUFF_TARGET_VERSION" --check --diff -- "${python_files[@]}"
	ruff check --isolated --no-cache --target-version "$RUFF_TARGET_VERSION" --select "$RUFF_SELECT" --ignore "$RUFF_IGNORE" -- "${python_files[@]}"
fi
